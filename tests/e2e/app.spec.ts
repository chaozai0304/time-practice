test('学习小岛支持 3D 暂停或无 WebGL 静态回退', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await setup(page)
  const island = page.locator('.motion-island')
  await expect(island).toHaveAttribute('data-ready', 'true')
  await expect(island).toHaveAttribute('data-motion', /^(3d|static)$/, { timeout: 30_000 })
  if (await island.getAttribute('data-motion') === '3d') {
    await expect(island.locator('canvas')).toBeVisible()
    await page.getByRole('button', { name: '暂停小岛动画' }).click()
    await expect(page.getByRole('button', { name: '播放小岛动画' })).toHaveAttribute('aria-pressed', 'true')
    await expect(island).toHaveAttribute('data-playing', 'false')
    await page.getByRole('button', { name: '播放小岛动画' }).click()
    await expect(page.getByRole('button', { name: '暂停小岛动画' })).toHaveAttribute('aria-pressed', 'false')
  } else {
    await expect(island.locator('.island-fallback')).toBeVisible()
  }
  await island.screenshot({ path: `test-results/island-${info.project.name}.png` })
})
